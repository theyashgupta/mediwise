import { patterns } from "../patterns/catalog.js";
import { categoryLabel, localizeAlertHeadline, localizeFollowUp, localizeVerdict } from "../localize.js";
import { alertHeadlineStart } from "../findings.js";
import { followUpTemplates } from "../follow-ups.js";
import { categorySchema } from "./schema.js";
import { hindiGroups, hindiPatternText } from "./hi/index.js";
import { derived, markers, studyMarkers } from "./index.js";
import { hindiSentences, markerText } from "./text.js";

const fieldNames = {
  description: "Short description",
  whatItIs: "What it is",
  whyItMatters: "Why it matters",
  whatMovesIt: "What moves it",
  southAsianNote: "South Asian note",
} as const;

function pair(label: string, english: string, hindi: string) {
  const lines = (text: string) => hindiSentences(text).map((sentence) => `  - ${sentence}`);
  return [`**${label}**`, "", "- EN:", ...lines(english), "- HI:", ...lines(hindi), ""];
}

/**
 * Writes the medical review list: every Hindi catalog and engine sentence beside its English source.
 *
 * @remarks
 * The list is generated from the code, and a test fails when the committed copy differs, so it never drifts from the shipped text.
 */
export function hindiReviewMarkdown(): string {
  const entries = new Map([...markers, ...derived, ...studyMarkers].map((entry) => [entry.key, entry]));
  const out = [
    "# Hindi catalog review",
    "",
    "Generated by `pnpm --filter @mediwise/api review:hindi` from `packages/engine/src/catalog/hi`. Do not edit this file. Change the Hindi file and run the command again.",
    "",
    "## How to review",
    "",
    "1. Read each Hindi sentence (HI) against its English source (EN).",
    "2. Check that the meaning is the same. Check that each hedge stays a hedge: \"may be low\" must not become \"is low\".",
    "3. Check that each number and each printed name (HbA1c, LDL) is the same as in the English.",
    "4. Put an x in the box of a marker when all of its sentences are correct. Write each correction under the marker.",
    "",
  ];
  for (const [group, texts] of Object.entries(hindiGroups)) {
    out.push(`## Group: ${group}`, "");
    for (const [key, hindi] of Object.entries(texts)) {
      const entry = entries.get(key);
      if (!entry) continue;
      const english = markerText(entry, "en");
      out.push(`### ${key}`, "", `- [ ] ${entry.name}${entry.shortName ? ` (${entry.shortName})` : ""}`, "");
      for (const [field, label] of Object.entries(fieldNames) as [keyof typeof fieldNames, string][]) {
        const source = english[field];
        const text = hindi[field];
        if (source && text) out.push(...pair(label, source, text));
      }
      (english.textRuleFollowUps ?? []).forEach((followUp, i) => {
        const text = hindi.textRuleFollowUps?.[i];
        if (!text) return;
        for (const part of ["title", "why", "next"] as const) {
          out.push(...pair(`Follow-up ${i + 1}, ${part}`, followUp[part], text[part]));
        }
      });
    }
  }
  out.push("## Patterns", "");
  for (const pattern of patterns) {
    const hindi = hindiPatternText[pattern.key];
    if (!hindi) continue;
    out.push(`### ${pattern.key}`, "", `- [ ] ${pattern.name}`, "");
    for (const field of ["name", "description", "whatItSuggests", "whatToDo"] as const) {
      out.push(...pair(field, pattern[field], hindi[field]));
    }
  }
  out.push(
    "## Engine sentences",
    "",
    "The engine builds these sentences from a template. The counts, the marker name and the catalog text change per report. The examples use real catalog entries.",
    "",
    "### Verdict",
    "",
    "- [ ] Verdict templates",
    "",
  );
  for (const verdict of [
    "We could not check any marker on this report against a calibrated range.",
    "All 12 markers sit in your calibrated ranges. Nothing needs to move first.",
    "67 of 81 markers sit in your calibrated ranges. LDL cholesterol is the one to move first.",
  ]) {
    out.push(...pair("Verdict", verdict, localizeVerdict(verdict, "hi")));
  }
  out.push("### Follow-ups", "", "- [ ] Follow-up templates", "");
  for (const [kind, key] of [
    ["supplement", "vitamin_d"],
    ["retest", "ldl_cholesterol"],
    ["measure", "insulin_fasting"],
  ] as const) {
    const entry = entries.get(key)!;
    const english = { kind, markerKey: key, ...followUpTemplates[kind](entry) };
    const hindi = localizeFollowUp(english, "hi");
    for (const part of ["title", "why", "next"] as const) {
      out.push(...pair(`${kind}, ${part}`, english[part], hindi[part]));
    }
  }
  const headline = `${alertHeadlineStart}X-ray and ultrasound reports.`;
  out.push("### Alert headline", "", "- [ ] Alert headline template", "");
  out.push(...pair("Alert headline", headline, localizeAlertHeadline(headline, "hi")));
  out.push("### Category labels", "", "- [ ] Category labels", "");
  for (const key of categorySchema.options) {
    out.push(`- ${categoryLabel(key, "en")}: ${categoryLabel(key, "hi")}`);
  }
  return `${out.join("\n").trimEnd()}\n`;
}
